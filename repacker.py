#!/data/data/com.termux/files/usr/bin/env python
"""
repacker.py — Repack installed Python packages into wheel files.

Designed for Termux ($PREFIX/lib/python3.14/site-packages) but works on any CPython installation that stores packages in *.dist-info directories.

For each selected package the script:

1. Reads the package's RECORD file to learn which files belong to it. 2. Skips .pyc/.pyo files (regenerated by the interpreter) and stale signature files (*.jws / *.p7s). 3. Re-maps out-of-site-packages files into the wheel's .data hierarchy: * $PREFIX/bin/<script> → <name>-<version>.data/scripts/<script> * $PREFIX/share/<path> → <name>-<version>.data/data/share/<path> * any other path under $PREFIX → <name>-<version>.data/data/<path> (so pip restores them to their original location on install) 4. Re-writes RECORD so it only lists files actually placed in the wheel. 5. Zips everything into <name>-<version>-<tag>.whl under ~/tmp/whl.

The **wheel tag** (<pyver>-<abi>-<plat>) is always read from the WHEEL file inside the *.dist-info directory (first Tag: line). Packages whose WHEEL is missing or has no valid Tag are skipped with an error.

Usage ----- python repacker.py -a # repack every installed package python repacker.py a # packages whose name starts with 'a' (case-insens.) python repacker.py --pure # every pure-Python package python repacker.py --none-pure # every non-pure (compiled/platform) package python repacker.py req --pure # prefix 'req' AND pure python repacker.py -a --none-pure # all non-pure python repacker.py -a -j 4 # 4 parallel workers python repacker.py -a -o /tmp/wheels # custom output directory

"""

from __future__ import annotations

import argparse
import contextlib
import csv
import io
import os
import re
import sys
import zipfile
from concurrent.futures import ProcessPoolExecutor, as_completed
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

from loguru import logger

# zlib is required for ZIP_DEFLATED; degrade gracefully if unavailable.
try:
    import zlib  # noqa: F401

    _COMPRESSION = zipfile.ZIP_DEFLATED
except ImportError:  # pragma: no cover - very unusual on CPython
    _COMPRESSION = zipfile.ZIP_STORED


# ---------------------------------------------------------------------------
# Data model
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class PackageInfo:
    """Metadata gathered for a single installed package."""

    dist_info_dir: Path
    """Path to the ``*.dist-info`` directory."""

    name: str
    """Distribution name as it appears in the dist-info folder (may contain ``_``)."""

    version: str
    """Version string taken from the dist-info folder name."""

    tag: str
    """Wheel compatibility tag, e.g. ``py3-none-any`` or ``cp311-cp311-linux_aarch64``."""


# ---------------------------------------------------------------------------
# Name / tag helpers
# ---------------------------------------------------------------------------

_NAME_RE = re.compile(r"[^\w\d.]+", re.UNICODE)
_TAG_RE = re.compile(r"^[\w.]+-[\w.]+-[\w.]+$")


def normalize_name(name: str) -> str:
    """Return *name* escaped for use in wheel paths (PEP 427)."""
    return _NAME_RE.sub("_", name)


def read_wheel_tag(wheel_file: Path) -> Optional[str]:
    """
    Return the first valid ``Tag:`` from *wheel_file*.

    Returns ``None`` if the file is missing, unreadable, or contains no valid
    tag. ``WHEEL`` is the authoritative source for the tag; we never guess.
    """
    if not wheel_file.is_file():
        return None
    try:
        with wheel_file.open("r", encoding="utf-8", errors="replace") as fh:
            for line in fh:
                if line.startswith("Tag:"):
                    tag = line.split(":", 1)[1].strip()
                    if _TAG_RE.match(tag):
                        return tag
                    logger.warning(f"malformed tag {tag!r} in {wheel_file}")
                    return None
    except OSError as exc:
        logger.warning(f"could not read {wheel_file}: {exc}")
    return None


def is_pure_python(tag: str) -> bool:
    """Return ``True`` iff *tag* denotes a pure-Python wheel (abi=none, plat=any)."""
    parts = tag.split("-")
    if len(parts) != 3:
        return False
    _, abi, platform = parts
    return abi == "none" and platform == "any"


# ---------------------------------------------------------------------------
# Discovery
# ---------------------------------------------------------------------------


def find_packages(site_packages: Path) -> list[PackageInfo]:
    """Enumerate installed packages by scanning ``*.dist-info`` folders."""
    packages: list[PackageInfo] = []
    for dist_info in sorted(site_packages.glob("*.dist-info")):
        if not dist_info.is_dir():
            continue
        stem = dist_info.name[: -len(".dist-info")]
        name, sep, version = stem.rpartition("-")
        if not sep or not name:
            logger.warning(f"skipping {dist_info.name}: cannot parse name/version")
            continue
        tag = read_wheel_tag(dist_info / "WHEEL")
        if tag is None:
            logger.error(f"skipping {dist_info.name}: missing or invalid WHEEL Tag")
            continue
        packages.append(
            PackageInfo(
                dist_info_dir=dist_info,
                name=name,
                version=version,
                tag=tag,
            )
        )
    return packages


# ---------------------------------------------------------------------------
# RECORD parsing / writing
# ---------------------------------------------------------------------------


def parse_record(record_path: Path) -> list[tuple[str, str, str]]:
    """Parse a ``RECORD`` CSV file into ``(path, hash, size)`` tuples."""
    rows: list[tuple[str, str, str]] = []
    with record_path.open("r", encoding="utf-8", newline="") as fh:
        for row in csv.reader(fh):
            if not row:
                continue
            while len(row) < 3:
                row.append("")
            rows.append((row[0], row[1], row[2]))
    return rows


def render_record(entries: list[tuple[str, str, str]]) -> str:
    """Serialise *entries* back into RECORD CSV text (``\\n`` line endings)."""
    buf = io.StringIO()
    csv.writer(buf, lineterminator="\n").writerows(entries)
    return buf.getvalue()


# ---------------------------------------------------------------------------
# Single-package repack
# ---------------------------------------------------------------------------


def repack_package(
    site_packages: Path,
    prefix: Path,
    pkg: PackageInfo,
    out_dir: Path,
) -> Optional[Path]:
    """
    Repack *pkg* into ``out_dir`` and return the resulting wheel path.

    Scripts (``$PREFIX/bin``) and data files (``$PREFIX/share`` and any other
    path under ``$PREFIX``) are placed into the wheel's ``.data`` tree so pip
    re-creates them at the correct location.

    Returns ``None`` on any failure (errors are logged).
    """
    logger.info(f"[start] {pkg.name}=={pkg.version} (tag={pkg.tag})")

    record_path = pkg.dist_info_dir / "RECORD"
    if not record_path.is_file():
        logger.error(f"[fail]  {pkg.name}: no RECORD in {pkg.dist_info_dir}")
        return None

    try:
        rows = parse_record(record_path)
    except Exception as exc:
        logger.error(f"[fail]  {pkg.name}: cannot parse RECORD: {exc}")
        return None

    record_rel = record_path.relative_to(site_packages).as_posix()
    wheel_data_prefix = f"{normalize_name(pkg.name)}-{normalize_name(pkg.version)}.data"
    scripts_dir = prefix / "bin"

    files_to_add: list[tuple[Path, str]] = []  # (abs_path, wheel_arcname)
    new_record: list[tuple[str, str, str]] = []
    n_lib = n_scripts = n_data = 0
    skipped_pyc = skipped_sig = 0
    missing: list[str] = []
    skipped_external: list[str] = []

    for rel_path, hash_val, size in rows:
        rel_posix = rel_path.replace("\\", "/")

        # RECORD itself is regenerated at the end.
        if rel_posix == record_rel:
            continue

        # Regenerated bytecode and stale signatures.
        if rel_posix.endswith((".pyc", ".pyo")):
            skipped_pyc += 1
            continue
        if rel_posix.endswith((".jws", ".p7s")):
            skipped_sig += 1
            continue

        # Normalise `..` without resolving symlinks; the resulting path is
        # still absolute and file operations work on it directly.
        abs_path = Path(os.path.normpath(site_packages / rel_posix))

        # Classify into wheel layout.
        try:
            arcname = abs_path.relative_to(site_packages).as_posix()
            kind = "lib"
        except ValueError:
            try:
                inside_bin = abs_path.relative_to(scripts_dir)
                arcname = f"{wheel_data_prefix}/scripts/{inside_bin.as_posix()}"
                kind = "scripts"
            except ValueError:
                try:
                    inside_prefix = abs_path.relative_to(prefix)
                    arcname = f"{wheel_data_prefix}/data/{inside_prefix.as_posix()}"
                    kind = "data"
                except ValueError:
                    skipped_external.append(rel_posix)
                    continue

        if not abs_path.is_file():
            missing.append(rel_posix)
            continue

        files_to_add.append((abs_path, arcname))
        new_record.append((arcname, hash_val, size))
        if kind == "lib":
            n_lib += 1
        elif kind == "scripts":
            n_scripts += 1
        else:
            n_data += 1

    for item in missing:
        logger.warning(f"[miss]  {pkg.name}: missing file {item}")
    for item in skipped_external:
        logger.warning(f"[skip]  {pkg.name}: outside prefix: {item}")

    if not files_to_add:
        logger.error(f"[fail]  {pkg.name}: nothing to pack")
        return None

    # RECORD of the wheel itself (no hash, no size) must be appended last.
    new_record.append((record_rel, "", ""))

    wheel_name = (
        f"{normalize_name(pkg.name)}-{normalize_name(pkg.version)}-{pkg.tag}.whl"
    )
    wheel_path = out_dir / wheel_name

    try:
        with zipfile.ZipFile(wheel_path, "w", compression=_COMPRESSION) as zf:
            for abs_path, arcname in files_to_add:
                zf.write(abs_path, arcname)
            zf.writestr(record_rel, render_record(new_record))
    except Exception as exc:
        logger.error(f"[fail]  {pkg.name}: writing {wheel_name}: {exc}")
        with contextlib.suppress(OSError):
            wheel_path.unlink(missing_ok=True)
        return None

    logger.success(
        f"[done]  {pkg.name}=={pkg.version} -> {wheel_name} "
        f"({n_lib} lib, {n_scripts} script, {n_data} data; "
        f"skipped {skipped_pyc} pyc, {skipped_sig} sig, {len(missing)} missing)"
    )
    return wheel_path


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="repacker.py",
        description="Repack installed Python packages into wheel files.",
    )
    parser.add_argument(
        "-a",
        "--all",
        action="store_true",
        help="repack every installed package",
    )
    parser.add_argument(
        "prefix",
        nargs="?",
        default=None,
        help="only repack packages whose name starts with this prefix (case-insensitive)",
    )
    purity = parser.add_mutually_exclusive_group()
    purity.add_argument(
        "--pure",
        action="store_true",
        help="only pure-Python packages (abi=none, platform=any)",
    )
    purity.add_argument(
        "--none-pure",
        dest="none_pure",
        action="store_true",
        help="only non-pure (compiled / platform-specific) packages",
    )
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        default=Path.home() / "tmp" / "whl",
        help="output directory (default: ~/tmp/whl)",
    )
    parser.add_argument(
        "-j",
        "--jobs",
        type=int,
        default=None,
        help="parallel workers (default: CPU count)",
    )
    parser.add_argument(
        "--site-packages",
        type=Path,
        default=None,
        help="site-packages directory to scan (default: current directory)",
    )
    return parser


def main(argv: Optional[list[str]] = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)

    if args.all and args.prefix:
        parser.error("cannot combine -a/--all with a prefix")
    if not (args.all or args.prefix or args.pure or args.none_pure):
        parser.error("provide -a/--all, a prefix, --pure, or --none-pure")

    # `Path.cwd()` is already absolute; abspath also normalises any `..` given
    # via --site-packages and does NOT follow symlinks.
    site_packages = Path(os.path.abspath(args.site_packages or Path.cwd()))
    if not site_packages.is_dir():
        logger.error(f"not a directory: {site_packages}")
        return 1

    # $PREFIX/bin is exactly $PREFIX/lib/pythonX.Y/site-packages/../../../bin
    prefix = site_packages.parent.parent.parent
    if not (prefix / "bin").is_dir():
        logger.warning(
            f"prefix {prefix} has no bin/ directory; scripts will not be included"
        )

    out_dir: Path = args.output.expanduser().resolve()
    try:
        out_dir.mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        logger.error(f"cannot create output directory {out_dir}: {exc}")
        return 1

    logger.info(f"site-packages: {site_packages}")
    logger.info(f"prefix:        {prefix}")
    logger.info(f"output dir:    {out_dir}")
    logger.info("scanning for installed packages ...")

    packages = find_packages(site_packages)
    logger.info(f"found {len(packages)} package(s)")

    selected = packages
    if args.prefix and not args.all:
        pfx = args.prefix.lower()
        selected = [p for p in selected if p.name.lower().startswith(pfx)]
    if args.pure:
        selected = [p for p in selected if is_pure_python(p.tag)]
    elif args.none_pure:
        selected = [p for p in selected if not is_pure_python(p.tag)]

    if not selected:
        logger.warning("no packages matched the selection")
        return 0

    logger.info(f"selected {len(selected)} package(s):")
    for pkg in selected:
        logger.info(f"  - {pkg.name}=={pkg.version} ({pkg.tag})")

    failures: list[str] = []
    with ProcessPoolExecutor(max_workers=args.jobs) as pool:
        futures = {
            pool.submit(repack_package, site_packages, prefix, pkg, out_dir): pkg
            for pkg in selected
        }
        for fut in as_completed(futures):
            pkg = futures[fut]
            try:
                if fut.result() is None:
                    failures.append(pkg.name)
            except Exception as exc:  # pragma: no cover - defensive
                logger.exception(f"[fail]  {pkg.name}: unexpected error: {exc}")
                failures.append(pkg.name)

    if failures:
        logger.warning(f"{len(failures)} package(s) failed: {', '.join(failures)}")
        return 1
    logger.success(f"repacked {len(selected)} package(s) to {out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
